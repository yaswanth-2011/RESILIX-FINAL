def main() -> int:
    failures = []
    touched = {}
    for rel, old, new, count in EDITS:
        path = ROOT / rel
        text = touched.get(rel)
        if text is None:
            text = path.read_text()
        occurrences = text.count(old)
        if occurrences != count:
            failures.append(f"{rel}: expected {count} occurrence(s) of {old[:60]!r}, found {occurrences}")
            continue
        text = text.replace(old, new)
        touched[rel] = text
    if failures:
        print("FAILED EDITS:")
        for f in failures:
            print("  -", f)
        return 1
    for rel, text in touched.items():
        (ROOT / rel).write_text(text)
    print(f"applied {len(EDITS)} edits across {len(touched)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
